// Command gen writes secrets_gen.go from the whitelisted .env values (run by
// `go generate ./backend/internal/secrets`). NSONLINE_ENV_FILE replaces -env.
// A missing .env embeds nothing. It never prints values, only key names.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"sort"

	"nsonline/internal/env"
	"nsonline/internal/secrets"
	"nsonline/internal/secrets/seal"
)

func main() {
	envPath := flag.String("env", "../../../.env", ".env file to read (NSONLINE_ENV_FILE overrides)")
	out := flag.String("out", "secrets_gen.go", "Go file to write")
	flag.Parse()
	if p := os.Getenv("NSONLINE_ENV_FILE"); p != "" {
		*envPath = p
	}
	keys, err := generate(*envPath, *out)
	if err != nil {
		log.Fatalf("secrets/gen: %v", err)
	}
	if len(keys) == 0 {
		fmt.Fprintf(os.Stderr, "secrets/gen: no values embedded (%s missing or empty): the binary will need a .env or environment variables\n", *envPath)
		return
	}
	fmt.Fprintf(os.Stderr, "secrets/gen: embedded %d keys: %v\n", len(keys), keys)
}

func generate(envPath, outPath string) ([]string, error) {
	values, err := readEnv(envPath)
	if err != nil {
		return nil, err
	}
	src, err := render(values)
	if err != nil {
		return nil, err
	}
	if err := writeAtomic(outPath, src); err != nil {
		return nil, err
	}
	keys := make([]string, 0, len(values))
	for k := range values {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys, nil
}

func readEnv(path string) (map[string]string, error) {
	f, err := os.Open(path)
	if errors.Is(err, fs.ErrNotExist) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, err
	}
	defer f.Close()
	all, err := env.Parse(f)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	out := map[string]string{}
	for _, k := range secrets.Keys {
		if v := all[k]; v != "" {
			out[k] = v
		}
	}
	return out, nil
}

const shares = 3

func render(values map[string]string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by nsonline/internal/secrets/gen; DO NOT EDIT.\n")
	buf.WriteString("// Obfuscated build-time configuration (not encryption you can rely on). Gitignored.\n\n")
	buf.WriteString("package secrets\n\n")
	if len(values) == 0 {
		buf.WriteString("// No values were embedded: configuration comes from the environment only.\n")
		return format.Source(buf.Bytes())
	}
	key, err := seal.NewKey()
	if err != nil {
		return nil, err
	}
	blob, err := seal.Seal(values, key)
	if err != nil {
		return nil, err
	}
	parts, err := seal.Split(key, shares)
	if err != nil {
		return nil, err
	}
	buf.WriteString("func init() {\n\tsealed = ")
	writeBytes(&buf, blob)
	buf.WriteString("\n\tkeyShares = [][]byte{\n")
	for _, p := range parts {
		buf.WriteString("\t\t")
		writeBytes(&buf, p)
		buf.WriteString(",\n")
	}
	buf.WriteString("\t}\n}\n")
	return format.Source(buf.Bytes())
}

func writeBytes(buf *bytes.Buffer, b []byte) {
	buf.WriteString("[]byte{")
	for i, c := range b {
		if i%16 == 0 {
			buf.WriteString("\n\t\t")
		}
		fmt.Fprintf(buf, "0x%02x, ", c)
	}
	buf.WriteString("\n\t}")
}

func writeAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".secrets-gen-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
